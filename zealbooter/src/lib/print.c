static struct limine_framebuffer *g_fb;
static uint32_t g_fg = 0x00FFFFFF;
static uint32_t g_bg = 0x00000000;
static size_t g_col;
static size_t g_row;
static size_t g_cols;
static size_t g_rows;

static void fb_put_pixel(size_t x, size_t y, uint32_t color)
{
	uint8_t *row;
	uint32_t bpp_bytes;

	if (!g_fb || x >= g_fb->width || y >= g_fb->height)
		return;

	bpp_bytes = (g_fb->bpp + 7) / 8;
	row = (uint8_t *)g_fb->address + y * g_fb->pitch + x * bpp_bytes;
	if (g_fb->bpp >= 24) {
		row[0] = (uint8_t)(color & 0xFF);
		row[1] = (uint8_t)((color >> 8) & 0xFF);
		row[2] = (uint8_t)((color >> 16) & 0xFF);
		if (bpp_bytes >= 4)
			row[3] = 0;
	}
}

static void fb_clear(void)
{
	size_t y;

	if (!g_fb)
		return;
	for (y = 0; y < g_fb->height; y++)
		memset((uint8_t *)g_fb->address + y * g_fb->pitch, 0, g_fb->width * ((g_fb->bpp + 7) / 8));
}

static void fb_scroll(void)
{
	size_t y;
	size_t line_bytes;
	uint8_t *base;

	if (!g_fb)
		return;
	base = (uint8_t *)g_fb->address;
	line_bytes = g_fb->pitch * FONT_H;
	memmove(base, base + line_bytes, (g_rows - 1) * line_bytes);
	for (y = (g_rows - 1) * FONT_H; y < g_fb->height; y++)
		memset(base + y * g_fb->pitch, 0, g_fb->width * ((g_fb->bpp + 7) / 8));
	g_row = g_rows - 1;
	g_col = 0;
}

static void fb_draw_char(size_t col, size_t row, char c)
{
	const uint8_t *glyph;
	size_t gx, gy;
	size_t px, py;
	uint8_t bits;

	if (!g_fb)
		return;
	if (c < 0x20 || c > 0x7E)
		c = '?';
	glyph = font8x8[c - 0x20];
	px = col * FONT_W;
	py = row * FONT_H;
	for (gy = 0; gy < FONT_H; gy++) {
		bits = glyph[gy];
		for (gx = 0; gx < FONT_W; gx++)
			fb_put_pixel(px + gx, py + gy, (bits & (0x80 >> gx)) ? g_fg : g_bg);
	}
}

static void fb_putc(char c)
{
	if (!g_fb)
		return;
	if (c == '\r') {
		g_col = 0;
		return;
	}
	if (c == '\n') {
		g_col = 0;
		g_row++;
		if (g_row >= g_rows)
			fb_scroll();
		return;
	}
	if (c == '\t') {
		do {
			fb_putc(' ');
		} while (g_col & 3);
		return;
	}
	if (g_col >= g_cols) {
		g_col = 0;
		g_row++;
		if (g_row >= g_rows)
			fb_scroll();
	}
	fb_draw_char(g_col, g_row, c);
	g_col++;
}

bool fb_console_init(struct limine_framebuffer *fb)
{
	if (!fb || !fb->address || fb->width < FONT_W || fb->height < FONT_H || fb->bpp < 24)
		return false;

	g_fb = fb;
	g_cols = fb->width / FONT_W;
	g_rows = fb->height / FONT_H;
	g_col = 0;
	g_row = 0;
	fb_clear();
	return true;
}

int printf(const char *format, ...)
{
	va_list args;
	char buffer[PRINT_BUFFER_SIZE];
	size_t length;
	size_t i;

	va_start(args, format);
	length = (size_t)vsnprintf(buffer, PRINT_BUFFER_SIZE, format, args);
	va_end(args);

	if (length >= PRINT_BUFFER_SIZE)
		length = PRINT_BUFFER_SIZE - 1;

	for (i = 0; i < length; i++)
		fb_putc(buffer[i]);

	return (int)length;
}
